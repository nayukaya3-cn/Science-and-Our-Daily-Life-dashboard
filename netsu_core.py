SWEET_BAND = (55.0, 75.0)   # 甘くする酵素（β-アミラーゼ）が働く帯


def band_label(lo: int, hi: int | None) -> str:
    if hi is None:
        return f"{lo}℃以上"
    return f"{lo}℃前後" if lo == hi else f"{lo}〜{hi}℃"


def events_at(temp: float) -> list[str]:
    """その温度で起きていること（帯の上限なしは『以上』）"""
    return [what for lo, hi, what, _, _ in BANDS
            if (lo - 2 <= temp <= lo + 2 if lo == hi else temp >= lo and (hi is None or temp <= hi))]


# ─────────────────────────────────────────────
# 第5コマ：加熱の仕方で甘さは変わるか ─ 芋の中心温度の「説明用の模型」
# ─────────────────────────────────────────────
#   芋の中心は水分があるので 100℃ を大きく超えない。中心温度は 100℃ に向かってだんだん近づく、と単純化する。
#   tau（分）＝ 熱が中心に届く遅さ。大きいほどゆっくり温まる。数値は説明用で、実測ではない。
#   (条件, 加熱時間の目安（分）, tau（分）, 説明)
METHODS: list[tuple[str, float, float, str]] = [
    ("A 電子レンジ", 5.0, 1.5, "数分で中心まで熱くなる"),
    ("B 蒸す", 20.0, 6.0, "約20分"),
    ("C 小石を敷いた鍋（弱火）", 75.0, 25.0, "約60〜90分。外側からゆっくり"),
    ("D 低温のオーブン（約160℃）", 60.0, 18.0, "約60分以上"),
]
CORE_LIMIT = 100.0


def core_temp(t_min: float, tau: float, t0: float = 20.0) -> float:
    """加熱を始めて t 分後の中心温度（℃）。説明用の模型：100℃ との差が tau 分ごとに約1/2.7 になる"""
    return CORE_LIMIT - (CORE_LIMIT - t0) * math.exp(-t_min / tau)


def time_to(temp: float, tau: float, t0: float = 20.0) -> float:
    """中心が temp ℃ になるまでの時間（分）"""
    if temp <= t0:
        return 0.0
    return tau * math.log((CORE_LIMIT - t0) / (CORE_LIMIT - temp))


def minutes_in_band(tau: float, total_min: float, band: tuple[float, float] = SWEET_BAND, t0: float = 20.0) -> float:
    """加熱時間 total_min のうち、中心が band の温度帯にいた時間（分）"""
    enter, leave = time_to(band[0], tau, t0), time_to(band[1], tau, t0)
    return max(0.0, min(leave, total_min) - min(enter, total_min))


def method_table(t0: float = 20.0) -> list[dict]:
    return [{"条件": name, "加熱時間の目安（分）": total, "甘くなる帯（55〜75℃）にいた時間（分）":
             round(minutes_in_band(tau, total, t0=t0), 1), "メモ": memo} for name, total, tau, memo in METHODS]


# ─────────────────────────────────────────────
# 第6コマ：その比べ方はフェアか ─ Brix（糖度計）は「水が減っても」上がる
# ─────────────────────────────────────────────
def brix(solute_g: float, water_g: float) -> float:
    """Brix（％）＝ 溶けているもの ÷（溶けているもの＋水）× 100。糖だけでなく溶けているもの全体を測る"""
    return 100.0 * solute_g / (solute_g + water_g)


def brix_after(solute_g: float, water_g: float, water_loss: float, sugar_gain_g: float) -> float:
    """加熱後の Brix。water_loss＝水が飛んだ割合（0〜1）、sugar_gain_g＝酵素で増えた糖（g）"""
    return brix(solute_g + sugar_gain_g, water_g * (1 - water_loss))


