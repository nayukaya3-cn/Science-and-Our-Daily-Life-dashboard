_WEB = re.compile(r"https?://\S+")
_DATE = re.compile(r"(\d{4}\s*年\s*\d{1,2}\s*月\s*\d{1,2}\s*日|\d{4}[-/]\d{1,2}[-/]\d{1,2})")
_YEAR = re.compile(r"[（(]\s*\d{4}\s*年?\s*[）)]")


def check_reference(ref: str) -> list[str]:
    """参考文献1行を p.184 の書き方の例と照らし、足りないものを返す（空なら合格）"""
    r = ref.strip()
    if not r:
        return ["空欄です"]
    missing = []
    if _WEB.search(r) or "Web" in r or "ウェブ" in r:
        if not _WEB.search(r):
            missing.append("URL（https://…）")
        if not _DATE.search(r):
            missing.append("調べた日（例：2026年11月8日確認）")
        if "「" not in r:
            missing.append("「Webサイト名」")
        return missing
    if not _YEAR.search(r):
        missing.append("出版年（例：(2024年)）")
    if "『" not in r:
        missing.append("『書名』または『雑誌名』")
    if "「" not in r and not re.search(r"[（(][^）)]*(社|書店|出版|館|会|大学)[^）)]*[）)]", r):
        missing.append("（出版社）")
    return missing


def report_markdown(meta: dict[str, str], body: dict[str, str], refs: list[str]) -> str:
    """報告書の下書き（Markdown）。ダウンロード用で、サーバーには残さない"""
    lines = [f"# {meta.get('題目') or '（研究活動題目）'}", "",
             f"- 報告者：{meta.get('報告者') or '（未記入）'}／共同実験者：{meta.get('共同実験者') or '─'}",
             f"- 実施日：{meta.get('実施日') or '（未記入）'}", ""]
    for i, (item, how, _) in enumerate(REPORT_ITEMS[:-1], 1):
        lines += [f"## {i} {item}", body.get(item) or f"（未記入：{how}）", ""]
    lines += [f"## {len(REPORT_ITEMS)} 参考文献"]
    lines += [f"- {r}" for r in refs if r.strip()] or ["（未記入）"]
    lines += ["", "---", "※ 他の人の文章・写真・イラストは著作物。引用は「」でくくり出典を書く。"
              "教科書の紙面の写真は、報告書やWebに載せない。"]
    return "\n".join(lines)


