def soften_mark(name: str, temp: int) -> str:
    """第3コマの記録表（素材×温度）。〇＝形を保つ／△＝曲がり始める／×＝自重で曲がる／―＝もともと柔らかい"""
    s = FILAMENTS[name]["soften"]
    if s == 0:
        return "―"
    if s is None or temp < s - 5:
        return "〇"
    return "△" if temp <= s + 5 else "×"


def soften_table() -> list[dict]:
    return [{"素材": n, **{f"{t}℃": soften_mark(n, t) for t in BATH_TEMPS}} for n in FILAMENTS]


def first_soften(name: str) -> int | None:
    """記録表で、はじめて △ か × が付く温度（なければ None）"""
    return next((t for t in BATH_TEMPS if soften_mark(name, t) in "△×"), None)


