def fit_line(points: list[tuple[float, float]]) -> tuple[float, float]:
    """最小二乗法の回帰直線 y = a x + b（情報Ⅰ：データの活用）"""
    n = len(points)
    if n < 2:
        raise ValueError("点が2つ以上必要")
    mx, my = sum(x for x, _ in points) / n, sum(y for _, y in points) / n
    sxx = sum((x - mx) ** 2 for x, _ in points)
    if sxx == 0:
        raise ValueError("横軸の値が1種類しかない")
    a = sum((x - mx) * (y - my) for x, y in points) / sxx
    return a, my - a * mx


def correlation(points: list[tuple[float, float]]) -> float:
    """相関係数 r"""
    n = len(points)
    mx, my = sum(x for x, _ in points) / n, sum(y for _, y in points) / n
    sxx = sum((x - mx) ** 2 for x, _ in points)
    syy = sum((y - my) ** 2 for _, y in points)
    if sxx == 0 or syy == 0:
        raise ValueError("ばらつきがない")
    return sum((x - mx) * (y - my) for x, y in points) / (sxx * syy) ** 0.5


