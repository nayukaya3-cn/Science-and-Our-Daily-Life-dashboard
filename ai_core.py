def injection_flags(text: str | None) -> list[str]:
    """メール・Webページ・PDFなど『外から来た文章』をAIに読ませる前の点検。あやしい文の種類を返す（重複なし）"""
    t = _normalize(text)
    out = []
    for label, pat in _INJECTION:
        if pat.search(t) and label not in out:
            out.append(label)
    return out


