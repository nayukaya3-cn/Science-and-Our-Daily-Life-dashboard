def sticker_bar(height_cm: float, sticker: str = "🟩") -> str:
    """シールの棒グラフ：シール1枚＝1cm（四捨五入。0以下は空）"""
    return sticker * max(0, int(height_cm + 0.5))


def tallest(heights: dict[str, float]) -> list[str]:
    """いちばんふくらんだ場所（同じ高さなら全部）"""
    if not heights:
        return []
    top = max(heights.values())
    return [k for k, v in heights.items() if v == top]


def report_sentence(what: str, count: str, unknown: str) -> str:
    """「つたえる」カードの型：作業の報告と、理科の考察を同じ型にする"""
    return f"{what or '○○'}を{count or '△'}やりました。{unknown or '□□'}がわかりませんでした。"


