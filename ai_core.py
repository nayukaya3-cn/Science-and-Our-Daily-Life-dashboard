def beta_stats(good: int, bad: int, n: int = 4000, seed: int = 0) -> tuple[float, float, float]:
    """役に立った good 回・立たなかった bad 回のとき、『役に立つ見込み』の平均と、80％の幅（下・上）。
    はじめの見込みは 0〜1 のどこも同じ（ベータ分布 Beta(1,1)）。回数が少ないほど幅が広い"""
    g, b = max(0, int(good)), max(0, int(bad))
    rng = random.Random(seed)
    xs = sorted(rng.betavariate(g + 1, b + 1) for _ in range(n))
    return (g + 1) / (g + b + 2), xs[int(n * 0.1)], xs[int(n * 0.9)]


def pick_probs(rows: list[tuple[str, int, int]], n: int = 3000, seed: int = 0) -> dict[str, float]:
    """各使い方について見込みを1つずつ引き、いちばん大きいものを選ぶ…を n 回くり返したときの選ばれる割合（トンプソン抽出）。
    よく効くと分かっているもの（活用）と、まだ分からないもの（探索）の両方が選ばれる"""
    rows = [(str(name), max(0, int(g)), max(0, int(b))) for name, g, b in rows if str(name).strip()]
    if not rows:
        return {}
    rng = random.Random(seed)
    wins = dict.fromkeys((r[0] for r in rows), 0)
    for _ in range(n):
        best = max(rows, key=lambda r: rng.betavariate(r[1] + 1, r[2] + 1))
        wins[best[0]] += 1
    return {k: v / n for k, v in wins.items()}


