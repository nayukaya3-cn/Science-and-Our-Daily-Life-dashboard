def transfer_check(record: dict[str, dict[str, int]]) -> list[dict]:
    """同じカードを3場面で記録し、場面をまたいでレベルが保たれるかを見る（元版の『転移チェック』にあたる）。
    record[カード][場面] ＝ 1〜5。場面間の差が1以内なら「保たれている」"""
    rows = []
    for card in CARD_NAMES:
        lv = record.get(card, {})
        vals = [lv[s] for s in SCENES if s in lv]
        if not vals:
            continue
        gap = max(vals) - min(vals)
        low = [s for s in SCENES if lv.get(s) == min(vals)]
        rows.append({"カード": card, **{s: lv.get(s, "―") for s in SCENES}, "場面間の差": gap,
                     "転移": "保たれている" if gap <= 1 else f"「{'・'.join(low)}」で支援が多い → 次の手立てを考える場面"})
    return rows


