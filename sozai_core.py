WEAVES = {"平織（帆布）": (1, 1), "綾織（デニムの例：2本越えて1本くぐる）": (2, 1),
          "綾織（デニムの例：3本越えて1本くぐる）": (3, 1)}


def weave(kind: str, n: int = 12) -> list[list[int]]:
    """織りの組織図（n×n）。1＝たて糸が上、0＝よこ糸が上。
    たて糸が up 本越えて down 本くぐるのを、1段ごとに1本ずつずらす（情報Ⅰ：2次元配列と余り）"""
    up, down = WEAVES[kind]
    period = up + down
    return [[1 if (col - row) % period < up else 0 for col in range(n)] for row in range(n)]


def float_length(kind: str) -> int:
    """たて糸が表に続けて出る長さ（糸の浮き）。長いほど表面はなめらかで、斜めの畝が出る"""
    return WEAVES[kind][0]


