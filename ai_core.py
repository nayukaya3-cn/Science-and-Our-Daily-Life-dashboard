# 伏せ字にはしないが、相談してからにする話題（言葉だけでは個人を特定しないが、だれかの話なら要配慮）
_SENSITIVE = ("診断", "障害者手帳", "療育手帳", "受給者証", "通院", "服薬", "病歴", "既往歴")
SENSITIVE_KIND = "健康・障害・福祉に関する話題"


def _normalize(text: str | None) -> str:
    """全角の英数字・記号を半角にそろえる（全角の電話番号なども見つけられるように）"""
    return unicodedata.normalize("NFKC", text or "")


def _sweep(text: str | None) -> tuple[str, dict[str, int]]:
    out, counts = _normalize(text), {}
    for kind, _level, token, pat in _PATTERNS:
        def repl(m: re.Match, kind=kind, token=token) -> str:
            if kind.startswith("名前") and m.group(0).startswith(_NAME_STOP):
                return m.group(0)                       # 「皆さん」「お客様」などは名前ではない
            counts[kind] = counts.get(kind, 0) + 1
            return token
        out = pat.sub(repl, out)
    return out, counts


def scan(text: str | None) -> list[dict]:
    """AIに入れる前の点検。見つけたものを [{種類, 色, 件数}] で返す（赤が先）。見落としはある"""
    _, counts = _sweep(text)
    level = {kind: lv for kind, lv, *_ in _PATTERNS}
    rows = [{"種類": k, "色": level[k], "件数": n} for k, n in counts.items()]
    n_sens = sum(_normalize(text).count(w) for w in _SENSITIVE)
    if n_sens:
        rows.append({"種類": SENSITIVE_KIND, "色": "赤", "件数": n_sens})
    return sorted(rows, key=lambda r: -_LEVEL_ORDER[r["色"]])


def mask(text: str | None) -> str:
    """見つけたものを伏せ字（【メール】【電話】など）に置きかえた文章。話題の言葉（診断 など）はそのまま残る"""
    return _sweep(text)[0]


def light(findings: list[dict]) -> str:
    """点検結果の信号：赤が1つでもあれば赤、黄があれば黄、何もなければ緑（＝『見つからなかった』であって『安全』ではない）"""
    return max((f["色"] for f in findings), key=_LEVEL_ORDER.get, default="緑")


