    assert set(PAGE_TAG.values()) <= set(ids)
    assert all(c in CONCERNS for h in HINTS for c in h["concerns"])
    assert all(h["p"] in {"P1", "P2", "P3", "P4", "P5"} for h in HINTS)
    top = rank_hints("高校1年", "苦手を何とかしたい")[0]
    assert "苦手を何とかしたい" in top["concerns"]
    assert rank_hints("高校1年", "進路・将来を考えたい")[0]["explore"]          # 早い時期は探索寄りが先
    assert not rank_hints("直前期（12月〜）", "進路・将来を考えたい")[0]["explore"]  # 直前は活用寄りが先
    assert "（未記入）" in plan_sheet("高校2年", CONCERNS[0], {"戦略": ""})


