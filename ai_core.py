def build_prompt(parts: dict[str, str]) -> str:
    """質問の型を1つの文章に組み立てる。空の部品は飛ばす（『確かめ』だけは空でも決まり文句を入れる）"""
    lines = []
    for key, head, *_ in PROMPT_PARTS:
        v = (parts.get(key) or "").strip()
        if key == "check" and not v:
            v = DEFAULT_CHECK
        if v:
            lines.append(f"【{head}】{v}")
    return "\n".join(lines)


def prompt_score(parts: dict[str, str]) -> tuple[int, list[str]]:
    """5つの部品のうち書けた数と、まだ書いていない部品の見出し（『確かめ』は決まり文句が入るので数える）"""
    missing = [head for key, head, *_ in PROMPT_PARTS if key != "check" and not (parts.get(key) or "").strip()]
    return len(PROMPT_PARTS) - len(missing), missing


