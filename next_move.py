def rank_hints(stage: str, concern: str) -> list[dict]:
    """悩みに合うものを先に、同じなら時期（探索の多さ）に合うものを先に並べる"""
    w = STAGES[stage]

    def score(h: dict) -> float:
        fit = 1.0 if concern in h["concerns"] else 0.0
        stage_fit = w if h["explore"] else 1 - w
        return fit * 2 + stage_fit
    return sorted(HINTS, key=lambda h: -score(h))


def plan_sheet(stage: str, concern: str, rows: dict[str, str]) -> str:
    """『次の一手シート』をテキストにする（ダウンロード用。サーバーには残さない）"""
    w = STAGES[stage]
    lines = [
        "🚀 次の一手シート",
        "出発点の問い：動物の肉を食べても、その動物にならないのはなぜだろうか",
        f"答え（原理）：{PRINCIPLE}",
        f"時期：{stage}（探索 {w:.0%}・活用 {1 - w:.0%} の目安）／いまの悩み：{concern}",
        "",
    ]
    lines += [f"■ {k}\n{v or '（未記入）'}" for k, v in rows.items()]
    lines += ["", "※ ヒントは比喩。最後に決めるのは自分（設計図は自分の側にある）。"]
    return "\n".join(lines)


