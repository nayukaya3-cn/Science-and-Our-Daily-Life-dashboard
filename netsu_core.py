def _self_check() -> None:
    assert round(equilibrium(100, 0.80, 100, 100, 4.2, 20), 1) == 32.8          # 例題の答え（約33℃）
    t = {r["試料"]: r["水の温度（計算値）℃"] for r in exp3_table()}
    assert (round(t["アルミニウム"]), round(t["石"]), round(t["鉄"])) == (34, 33, 28)   # 単元案の予想値
    assert t["アルミニウム"] > t["石"] > t["鉄"]                                # 石が特別にためるわけではない
    # 出した熱量＝受け取った熱量
    te = equilibrium(100, 0.80, 100, 100, 4.2, 20)
    assert abs(heat(100, 0.80, 100 - te) - heat(100, 4.2, te - 20)) < 1e-6
    rows = {r["条件"][0]: r["甘くなる帯（55〜75℃）にいた時間（分）"] for r in method_table()}
    assert rows["A"] < rows["B"] < rows["D"] < rows["C"]                        # ゆっくり温めるほど帯に長くいる
    assert abs(core_temp(time_to(55, 25), 25) - 55) < 1e-9
    assert minutes_in_band(1.5, 0.1) == 0.0                                     # 帯に届く前に加熱をやめた
    assert brix_after(20, 80, 0.2, 0) > brix(20, 80)                            # 糖が増えなくても水が減れば上がる
    assert "メイラード" in "".join(events_at(180)) and not events_at(10)
    assert all(e["ans"] in e["opts"] for e in EXAMS)
    assert len(LESSONS) == 8 and len(TRANSFER) == 3


